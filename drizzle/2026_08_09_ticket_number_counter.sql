-- السبب: البلاغات كانت الكيان الوحيد بالمشروع الذي يُولَّد رقمه بالبحث عن
-- أعلى رقم موجود حاليًا (SELECT MAX) بدل عدّاد مستقل. النتيجة: حذف بلاغ
-- يحمل أعلى رقم يجعل الرقم يُعاد استخدامه لبلاغ جديد مختلف تمامًا.
--
-- حالة مؤكَّدة بالإنتاج قبل هذا الإصلاح:
--   MT-2026-00174 → كان لبلاغ "تجربه" (id=1800052، محذوف)، ثم أُعيد
--                    لبلاغ "Electrical" حقيقي (id=1800058)
--   MT-2026-00175 → كان لبلاغ "تجربه" (id=1800053، محذوف)، ثم أُعيد
--                    لبلاغ "Electrical" حقيقي (id=1800059)
--
-- ⚠️ البيانات لم تختلط إطلاقًا (الرقم الداخلي id فريد دائمًا ولا يُعاد)،
-- لكن تكرار رقم العرض يسبب لبسًا بصريًا وبالتقارير والمستندات المطبوعة.
--
-- النمط مطابق للعدّادات الستة الأخرى بالمشروع — AUTO_INCREMENT بقاعدة
-- البيانات هو ضامن التفرّد (آمن مع الطلبات المتزامنة بلا أقفال يدوية).
-- ============================================================

-- 1) الجدول
CREATE TABLE IF NOT EXISTS `ticket_number_counter` (
  `id`        INT NOT NULL AUTO_INCREMENT,
  `year`      INT NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
);

