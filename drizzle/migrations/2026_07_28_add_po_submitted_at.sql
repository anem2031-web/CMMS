-- إضافة عمود submittedAt لجدول purchase_orders
-- التاريخ: 2026-07-28
-- ══════════════════════════════════════════════════════════════════════════
--
-- المشكلة المعالَجة:
-- المستخدم ينشئ مسودة طلب شراء وقد تبقى أسبوعين قبل إرسالها رسميًا. كانت
-- القائمة تُرتَّب وتُفلتر بـcreatedAt (تاريخ إنشاء المسودة)، فيظهر الطلب عند
-- إرساله مدفونًا بين الطلبات القديمة بدل أن يظهر كطلب وصل حديثًا — فيضيع على
-- مدير الصيانة وتتوقف دورة الشراء عند أول مرحلة.
--
-- الحل:
-- عمود جديد submittedAt يُسجَّل لحظة تحويل المسودة إلى طلب رسمي، ويُستخدم
-- للترتيب والفلترة. عمود createdAt يبقى كما هو دون تعديل (لا نمسح حقيقة
-- تاريخية)، ويظل متاحًا لقياس مدة بقاء المسودة قبل الإرسال.
--
-- ملاحظة عن البيانات القائمة:
-- العمود يقبل NULL عمدًا. الطلبات الموجودة حاليًا ستبقى submittedAt = NULL،
-- والكود يستخدم COALESCE(submittedAt, createdAt) — أي أن ترتيبها الحالي لا
-- يتغيّر إطلاقًا، ولا حاجة لتعبئة رجعية أو تخمين تواريخ.

ALTER TABLE purchase_orders
  ADD COLUMN submittedAt TIMESTAMP NULL DEFAULT NULL
  COMMENT 'تاريخ تحويل المسودة إلى طلب رسمي — يُستخدم للترتيب والفلترة بدل createdAt';

-- فهرس لتسريع الترتيب/الفلترة على العمود الجديد
CREATE INDEX idx_po_submittedAt ON purchase_orders (submittedAt);
